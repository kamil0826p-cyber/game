import {
  maximumStrokeOnlyRatio,
  minimumFemaleReadabilityScore,
  minimumFrameParts,
  minimumFramePrimitives,
  minimumSheetPrimitives,
} from './outfit-generator-utils.mjs';

export const renderAuditMarkdown = (report) => {
  const weakest = [...report.records].sort((a, b) => a.qualityScore - b.qualityScore).slice(0, 12);
  const femaleWeakest = report.records
    .filter((record) => record.gender === 'FEMALE')
    .sort((a, b) => a.femaleReadability - b.femaleReadability)
    .slice(0, 10);
  const warningRows = report.records.filter((record) => record.warnings.length > 0).slice(0, 20);
  return `# Character outfit SVG audit

Generated by \`npm run outfits:audit\`. Do not edit measurements manually.

## Result

- Status: **${report.summary.status}**
- Sheets audited: **${report.summary.sheets}**
- Unique SHA-256 hashes: **${report.summary.uniqueHashes}**
- Unique structural signatures: **${report.summary.uniqueStructuralSignatures}**
- Minimum sheet primitives: **${report.summary.minimumSheetPrimitives}**
- Minimum frame primitives: **${report.summary.minimumFramePrimitives}**
- Minimum semantic layers per frame: **${report.summary.minimumFrameParts}**
- Minimum female readability: **${report.summary.minimumFemaleReadability}/100**
- Maximum stroke-only ratio: **${report.summary.maximumStrokeOnlyRatio}**
- Occlusion failures: **${report.summary.occlusionFailureCount}**
- Hard failures: **${report.summary.failureCount}**
- Advisory warnings: **${report.summary.warningCount}**

## Audit thresholds

| Metric | Required | Preferred |
|---|---:|---:|
| Primitives per sheet | ${minimumSheetPrimitives} | 1,120 |
| Primitives per frame | ${minimumFramePrimitives} | 70 |
| Semantic layers per frame | ${minimumFrameParts} | 14 |
| Female readability | ${minimumFemaleReadabilityScore} | 90 |
| Stroke-only ratio | ≤ ${maximumStrokeOnlyRatio} | ≤ 0.55 |
| Random body strokes | 0 | 0 |
| Hair on full helmet/hood | 0 | 0 |
| Unrequested horns | 0 | 0 |

## Lowest composite quality scores

| Outfit | Gender | Class | Score | Sheet primitives | Weakest frame | Layers | Female readability | Stroke-only | Head occlusion |
|---|---|---|---:|---:|---:|---:|---:|---:|---|
${weakest.map((record) => `| ${record.key} | ${record.gender} | ${record.characterClass} | ${record.qualityScore} | ${record.sheetPrimitives} | ${record.minimumFramePrimitives} | ${record.minimumFrameParts} | ${record.gender === 'FEMALE' ? record.femaleReadability : '—'} | ${record.strokeOnlyRatio} | ${record.head.occlusion} |`).join('\n')}

## Female readability review

| Outfit | Score | Shoulder / hip | Waist / hip | Hand | Foot | Hair visibility | Notes |
|---|---:|---:|---:|---:|---:|---:|---|
${femaleWeakest.map((record) => `| ${record.key} | ${record.femaleReadability} | ${record.silhouette.shoulderHipRatio} | ${record.silhouette.waistHipRatio} | ${record.silhouette.handSize} | ${record.silhouette.footSize} | ${record.head.visibleHair} | ${record.warnings.filter((warning) => warning.includes('female') || warning.includes('ratio')).join('; ') || 'passes preferred review'} |`).join('\n')}

## Advisory improvement queue

${warningRows.length === 0 ? 'No advisory warnings.' : warningRows.map((record) => `- **${record.key} / ${record.gender}:** ${record.warnings.join('; ')}.`).join('\n')}

## Clean rendering guarantees

- Full helmets and hoods suppress hair geometry rather than drawing strands over metal or fabric.
- Horn geometry is allowed only for head styles explicitly containing \`horn\` or \`antler\`.
- Material detail is clipped to the torso silhouette.
- Ambient particles are placed outside the body silhouette and rendered behind the character.
- Random body micro-strokes and duplicate head/weapon overlays are disabled.
- Filled masses, material panels, seams, controlled highlights, and class motifs replace line-noise detail.
- Every direction and walk frame keeps independent pose metadata and deterministic output.

## Next visual improvements

Prioritize entries with the lowest score or highest stroke-only ratio. Visual contact-sheet review at the final 48x72 footprint remains required before merging art-direction changes.
`;
};
